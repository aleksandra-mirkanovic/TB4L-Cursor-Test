export function getRecentlyUpdatedResources() {
  return [...allResources()].sort((a, b) => {
    const order = { fresh: 0, current: 1, aging: 2 };
    return (order[a.freshness] ?? 1) - (order[b.freshness] ?? 1);
  });
}

